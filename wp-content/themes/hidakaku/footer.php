jQuery(document).ready(function ($) {
    $('.product_pagination').not('#js-pagination').remove();

    const PER_PAGE = 12;
    let currentPage = 1;
    let $paginationItems = $('.product_col');

    function addSelectedCat(catName, catId) {
        if ($('.product_rs01_item a[data-cat-id="' + catId + '"]').length === 0) {
            const $item = $(`
                <li>
                    <a href="#" class="selected-cat" data-cat-id="${catId}">
                        ${catName}
                    </a>
                </li>
            `);

            $item.find('.selected-cat').on('click', function (e) {
                e.preventDefault();
                $(this).parent().remove();
                filterProducts();
                console.log('hi');
            });

            $('.product_rs01_item ul').append($item);
        }
    }

    // FILTER PRODUCTS
    function filterProducts() {

        let selectedCats = [];
        $('.selected-cat').each(function () {
            selectedCats.push(String($(this).data('cat-id')));
        });

        currentPage = 1;

        if (selectedCats.length === 0) {
            $paginationItems = $('.product_col');
            paginateItems();
            return;
        }

        let $matched = $();
        $('.product_col').each(function () {
            const itemIds = String($(this).data('cat-ids') || '')
                .split(',')
                .map(id => id.trim());

            if (selectedCats.some(id => itemIds.includes(id))) {
                $matched = $matched.add(this);
            }
        });

        $paginationItems = $matched;
        paginateItems();
    }
    function paginateItems() {
        const totalItems = $paginationItems.length;
        const totalPages = Math.ceil(totalItems / PER_PAGE);

        $('#js-pagination').empty();
        $('.product_col').hide();

        if (totalItems === 0) {
            updateDisplayCount();
            return;
        }

        const start = (currentPage - 1) * PER_PAGE;
        const end   = start + PER_PAGE;

        $paginationItems.slice(start, end).show();

        // if (totalPages > 1) {
            renderJsPagination(totalPages);
        // }

        updateDisplayCount();
    }
    paginateItems();

    $(document).on('click', '#js-pagination a', function () {
        console.log('CLICK JS');
    });

    // PAGINATION UI
    function renderJsPagination(totalPages) {
        let html = `
        <div class="product_pagi_flex">
            <div class="product_pagi_prev_all flexing">
        `;

        if (currentPage > 1) {
            html += `
                <p class="prev_start"><a role="button" data-page="1">最初へ</a></p>
                <p class="prev_item"><a role="button" data-page="${currentPage - 1}">前へ</a></p>
            `;
        } else {
            html += `
                <p class="prev_start disabled">最初へ</p>
                <p class="prev_item disabled">前へ</p>
            `;
        }

        html += `
            </div>
            <div class="product_pagi_page"><p>
        `;

        for (let i = 1; i <= totalPages; i++) {
            html += (i === currentPage)
                ? `<span class="current">${i}</span>`
                : `<span><a role="button" data-page="${i}">${i}</a></span>`;
        }

        html += `
            </p></div>
            <div class="product_pagi_next_all flexing">
        `;

        if (currentPage < totalPages) {
            html += `
                <p class="next_item"><a role="button" data-page="${currentPage + 1}">次へ</a></p>
                <p class="next_end"><a role="button" data-page="${totalPages}">最後へ</a></p>
            `;
        } else {
            html += `
                <p class="next_item disabled">次へ</p>
                <p class="next_end disabled">最後へ</p>
            `;
        }

        html += `
            </div>
        </div>
        `;

        $('#js-pagination').html(html);
    }

    // PAGINATION CLICK
    function updatePageUrl(page) {
        const baseUrl = window.location.origin + window.location.pathname.replace(/page\/\d+\/?$/, '');

        if (page === 1) {
            history.pushState({ page: 1 }, '', baseUrl);
        } else {
            history.pushState(
                { page },
                '',
                baseUrl.replace(/\/$/, '') + '/page/' + page + '/'
            );
        }
    }

    $(document).on('click', '#js-pagination a', function (e) {
        e.preventDefault();
        const page = parseInt($(this).data('page'));
        if (!page || page < 1) return;

        currentPage = page;
        paginateItems();
        updatePageUrl(page);
        $('html, body').animate({
            scrollTop: $('.product_flexin').offset().top - 150
        }, 0);
    });

    function updatePageUrl(page) {
        const baseUrl = window.location.origin + window.location.pathname.replace(/page\/\d+\/?$/, '');

        if (page === 1) {
            history.pushState({ page: 1 }, '', baseUrl);
        } else {
            history.pushState(
                { page },
                '',
                baseUrl.replace(/\/$/, '') + '/page/' + page + '/'
            );
        }
    }

    function getPageFromUrl() {
        const match = window.location.pathname.match(/page\/(\d+)/);
        return match ? parseInt(match[1]) : 1;
    }

    (function initPage() {
        currentPage = getPageFromUrl();
        $paginationItems = $('.product_col');
        const params = new URLSearchParams(window.location.search);
        const series = params.get('series');
        if (series) {
            const $link = $('.product-cat-link').filter(function () {
                return $(this).text().trim() === series.trim();
            });
            if ($link.length) {
                addSelectedCat(series, $link.data('cat-id'));
                filterProducts();
            }
        } else {
            paginateItems();
        }
    })();


    // SELECT / REMOVE CATEGORY
    $('.product-cat-link').on('click', function (e) {
        e.preventDefault();
        addSelectedCat($(this).text(), $(this).data('cat-id'));
        filterProducts();
    });

    $(document).on('click', '.selected-cat', function (e) {
        e.preventDefault();
        $(this).parent().remove();
        filterProducts();
        console.log('hi');
    });

    // COUNT
    function updateDisplayCount() {
        const total   = $paginationItems.length;
        const showing = $paginationItems.filter(':visible').length;
        $('#currentCount').text(showing + '/' + total);
    }

    // AUTO FILTER FROM URL (?series=)
    (function autoFilterFromUrl() {
        const params = new URLSearchParams(window.location.search);
        const series = params.get('series');
        if (!series) return;

        const $link = $('.product-cat-link').filter(function () {
            return $(this).text().trim() === series.trim();
        });

        if ($link.length) {
            addSelectedCat(series, $link.data('cat-id'));
        }
    })();

    // ===============================
    // INIT (JS PAGINATION FROM START)
    // ===============================
    (function initPage() {

        const hasSelected = $('.selected-cat').length > 0;

        if (hasSelected) {
            filterProducts();
        } else {
        currentPage = 1;
        $paginationItems = $('.product_col');
        paginateItems();
    }

    })();

});




